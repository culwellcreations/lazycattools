#!/usr/bin/env node
// Builds every Kitchen page from _build/kitchen/ingredients.json.
// Run from the repo root:  node _build/build-kitchen.mjs
// Writes: kitchen/index.html, kitchen/cups-to-grams/, one page per ingredient,
// one page per common amount, sitemap.xml, and the Kitchen block in llms.txt.
// Generated pages are overwritten on every run: edit the data or this script,
// never the generated HTML.

import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, readdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildToolPages } from './tool-pages.mjs';
import { loadGuides, buildGuidePages, guidesListHtml } from './guides.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const K = require(join(ROOT, 'assets/js/kitchen-converter.js'));
const DATA = JSON.parse(readFileSync(join(ROOT, '_build/kitchen/ingredients.json'), 'utf8'));
const SITE = 'https://lazycattools.com';
const CSS_SITE = '/assets/css/site.css?v=4';
const CSS_KITCHEN = '/assets/css/kitchen.css?v=4';
const JS_KITCHEN = '/assets/js/kitchen-converter.js?v=3';
const JS_RECIPE = '/assets/js/recipe-tools.js?v=2';

const ING = DATA.ingredients;
const GUIDES = loadGuides(ROOT);
const FAM = Object.fromEntries(DATA.families.map((f) => [f.id, f]));
const CUP_INGS = ING.filter((i) => i.mode === 'cup');
const bySlug = Object.fromEntries(ING.map((i) => [i.slug, i]));

// ── helpers ──────────────────────────────────────────────────────────────────
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const g = (n) => K.formatGrams(n);
const oz = (n) => K.formatOunces(n);
const vol = (grams, ing) => K.formatVolume(K.gramsToTsp(grams, ing.gpc));
const volText = (v) => (v.approx ? `<span class="approx">about</span> ${esc(v.text)}` : esc(v.text));
const volPlain = (v) => (v.approx ? `about ${v.text}` : v.text);

const ingUrl = (i) => `/kitchen/${i.slug}-${i.mode === 'spoon' ? 'teaspoons' : 'cups'}-to-grams/`;
const gramsUrl = (a) => `/kitchen/${a.g}-grams-to-cups/`;
const cupsUrl = (a) => `/kitchen/${a.slug}/`;
const ingTitle = (i) => `${i.name} ${i.mode === 'spoon' ? 'Teaspoons' : 'Cups'} to Grams`;

function write(urlPath, html) {
  const dir = join(ROOT, urlPath);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'index.html'), html);
}

