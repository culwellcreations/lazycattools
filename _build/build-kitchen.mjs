function crumbs(items) {
  const li = items.map(([name, path], idx) =>
    idx === items.length - 1 ? `<li aria-current="page">${esc(name)}</li>` : `<li><a href="${path}">${esc(name)}</a></li>`).join('');
  return `<nav class="crumbs" aria-label="Breadcrumb"><ol>${li}</ol></nav>`;
}

function crumbsLd(items) {
  return {
    '@type': 'BreadcrumbList',
    itemListElement: items.map(([name, path], idx) => ({ '@type': 'ListItem', position: idx + 1, name, item: SITE + path })),
  };
}

