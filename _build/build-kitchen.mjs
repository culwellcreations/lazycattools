const UNIT_OPTIONS = [['cup', 'cups'], ['tbsp', 'tablespoons'], ['tsp', 'teaspoons'], ['ml', 'milliliters'], ['g', 'grams'], ['oz', 'ounces']];

function converter({ slug, amount, unit, heading = 'Converter' }) {
  const groups = DATA.families.map((f) => {
    const opts = ING.filter((i) => i.family === f.id)
      .map((i) => `<option value="${i.slug}"${i.slug === slug ? ' selected' : ''}>${esc(i.name)}</option>`).join('');
    return `<optgroup label="${esc(f.name)}">${opts}</optgroup>`;
  }).join('');
  const units = UNIT_OPTIONS.map(([v, l]) => `<option value="${v}"${v === unit ? ' selected' : ''}>${l}</option>`).join('');
  const data = JSON.stringify(ING.map((i) => ({ slug: i.slug, lower: i.lower, gpc: i.gpc })));
  return `<form class="converter" data-kitchen-converter aria-label="${esc(heading)}">
      <div class="conv-row">
        <div class="conv-field">
          <label for="conv-amount">Amount</label>
          <input id="conv-amount" name="amount" type="text" inputmode="decimal" autocomplete="off" value="${esc(amount)}" aria-describedby="conv-error">
        </div>
        <div class="conv-field">
          <label for="conv-unit">Unit</label>
          <select id="conv-unit" name="unit">${units}</select>
        </div>
      </div>
      <div class="conv-field">
        <label for="conv-ingredient">Ingredient</label>
        <select id="conv-ingredient" name="ingredient">${groups}</select>
      </div>
      <p class="conv-error" id="conv-error" data-result-error hidden>Type a number, like 1, 1.5, 1 1/2 or ¾.</p>
      <div class="conv-result" aria-live="polite">
        <div class="conv-result-main" data-result-main>—</div>
        <div class="conv-result-sub" data-result-sub></div>
      </div>
      <p class="conv-note">US cups (236.6 ml). Fractions are rounded to the nearest ⅛.</p>
    </form>
    <script id="kitchen-data" type="application/json">${data}</script>
    <script src="${JS_KITCHEN}" defer></script>`;
}

