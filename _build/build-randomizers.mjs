// Builds the generated randomizer pages and keeps every randomizer linked.
// Run from the repo root: node _build/build-randomizers.mjs
//
// It writes:
//   - /tools/<slug>/index.html for each `built: 'gen'` tool, from
//     _build/randomizers/<slug>.mjs (the tool's controls, page text and FAQ)
//   - the "More randomizers" block (between randomizers:start/end markers)
//     on every randomizer page, hand-built ones included
//   - the Randomizers cards on the homepage (between markers)
//   - the Tools list in llms.txt (between markers)
// The sitemap is written by build-kitchen.mjs, which reads the same list.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { RANDOMIZERS, toolUrl } from './randomizers/list.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://lazycattools.com';
const CSS_SITE = '/assets/css/site.css?v=5';
const CSS_TOOL = '/assets/css/tool.css?v=1';
const JS_RAND = '/assets/js/rand.js?v=1';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const strip = (html) => String(html).replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

function replaceBlock(text, name, body, file) {
  const re = new RegExp(`(<!-- ${name}:start[^>]*-->)[\\s\\S]*?(<!-- ${name}:end -->)`);
  if (!re.test(text)) throw new Error(`${file}: missing ${name}:start/end markers`);
  return text.replace(re, `$1\n${body}\n$2`);
}

