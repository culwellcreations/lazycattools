// Builds the Word Games section. Run from the repo root:
//   node _build/build-word-games.mjs   (then node _build/build-kitchen.mjs for the sitemap)
//
// It writes:
//   - assets/js/wordlist.js, from _build/word-games/scowl-50-us.txt through
//     the filters in _build/word-games/filters.mjs
//   - /word-games/<slug>/index.html for each tool in _build/word-games/list.mjs,
//     from _build/word-games/<slug>.mjs (controls, page text, FAQ)
//   - the Word Games cards on the homepage and the Word Games block in
//     llms.txt (both between word-games:start/end markers)
// Script and style links carry a hash of the file, so browsers fetch a new
// copy whenever one changes. No version numbers to bump by hand.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { WORD_GAMES, wordGameUrl } from './word-games/list.mjs';
import { keep } from './word-games/filters.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://lazycattools.com';
const CSS_SITE = '/assets/css/site.css?v=5';
const CSS_TOOL = '/assets/css/tool.css?v=1';
const JS_RAND = '/assets/js/rand.js?v=1';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const strip = (html) => String(html).replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
const hash = (file) => createHash('sha1').update(readFileSync(join(ROOT, file))).digest('hex').slice(0, 8);

function replaceBlock(text, name, body, file) {
  const re = new RegExp(`(<!-- ${name}:start[^>]*-->)[\\s\\S]*?(<!-- ${name}:end -->)`);
  if (!re.test(text)) throw new Error(`${file}: missing ${name}:start/end markers`);
  return text.replace(re, `$1\n${body}\n$2`);
}

// ── 1. Word list ─────────────────────────────────────────────────────────────

const src = readFileSync(join(ROOT, '_build/word-games/scowl-50-us.txt'), 'utf8');
const [notice, body] = src.split(/\n---\n/);
const words = [...new Set(body.split(/\r?\n/).map((w) => w.trim()).filter(keep))].sort();
const byLen = {};
for (const w of words) (byLen[w.length] = byLen[w.length] || []).push(w);
const WORD_COUNT = words.length;
const ROUNDED = (Math.floor(WORD_COUNT / 1000) * 1000).toLocaleString('en-US'); // "60,000"

writeFileSync(join(ROOT, 'assets/js/wordlist.js'), `/*
Word list for the Lazy Cat Tools word games: ${WORD_COUNT.toLocaleString('en-US')} words, 2 to 15 letters,
grouped by length. Generated by _build/build-word-games.mjs from SCOWL/ESDB
(size 50, US spelling), filtered to lowercase a-z words with abbreviations
and offensive words removed. Don't edit by hand.

${notice.trim().split('\n').filter((l) => !/Git Revision/.test(l)).join('\n')}
*/
(function (root) {
  var W = {
${Object.keys(byLen).map((n) => `    ${n}: '${byLen[n].join(' ')}'`).join(',\n')}
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = W;
  else root.WORDLIST = W;
})(typeof window !== 'undefined' ? window : globalThis);
`);

const fill = (s) => String(s).replace(/\{\{WORDS\}\}/g, ROUNDED);

