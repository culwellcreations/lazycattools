let built = 0;
for (const t of WORD_GAMES) {
  const file = join(ROOT, '_build/word-games', `${t.slug}.mjs`);
  if (!existsSync(file)) { console.warn(`! ${t.slug}: no ${t.slug}.mjs yet, page not built`); continue; }
  const mod = await import(pathToFileURL(file).href);
  const dir = join(ROOT, 'word-games', t.slug);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'index.html'), page(t, mod.default));
  built++;
}

