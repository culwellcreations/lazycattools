function moreBlock(currentSlug) {
  const items = WORD_GAMES.filter((t) => t.slug !== currentSlug)
    .map((t) => `        <li><a href="${wordGameUrl(t)}">${esc(t.name)}</a></li>`).join('\n');
  return `  <nav class="more-tools" aria-labelledby="more-tools-heading">
    <div class="more-tools-inner">
      <h2 id="more-tools-heading">More word games</h2>
      <ul>
${items}
        <li><a href="/#word-games">All free tools</a></li>
      </ul>
    </div>
  </nav>`;
}

